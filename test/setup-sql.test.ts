// Charles — db/CHARLES-SETUP.sql is generated from db/, and must be current.
//
// The founder pastes that one file into a fresh Supabase project. If a
// migration or the seed changes and nobody re-runs `npm run setup-sql`, the
// paste would silently miss it. This rebuilds the script in-process and
// compares it with the committed file, ignoring only the date on the
// header line.

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build, ORDER } from "../scripts/build-setup-sql.mjs";

const SETUP = new URL("../db/CHARLES-SETUP.sql", import.meta.url);
const stripDate = (s: string) => s.replace(/^-- Generated by .* on \d{4}-\d{2}-\d{2} /m, "-- Generated by ");

test("db/CHARLES-SETUP.sql is exactly what scripts/build-setup-sql.mjs produces today", () => {
  assert.ok(existsSync(SETUP), "db/CHARLES-SETUP.sql is missing: run `npm run setup-sql`");
  const committed = readFileSync(SETUP, "utf8");
  assert.equal(stripDate(committed), stripDate(build()), "db/CHARLES-SETUP.sql is stale: run `npm run setup-sql` and commit the result");
});

test("every migration in db/ is in the script, and nothing in the script is missing from db/", () => {
  const dir = fileURLToPath(new URL("../db/", import.meta.url));
  for (const f of ORDER) assert.ok(existsSync(dir + f), `${f} is in ORDER but not in db/`);
  const onDisk = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f));
  assert.deepEqual([...onDisk].sort(), [...ORDER].sort(), "db/ and ORDER in scripts/build-setup-sql.mjs disagree");
});

test("the script starts with the base tables and ends with the library and the templates", () => {
  assert.equal(ORDER[0], "0000_base_tables.sql");
  assert.equal(ORDER[1], "0001_rls_lockdown.sql");
  assert.deepEqual(ORDER.slice(-4), ["0033_charles_schema.sql", "0034_charles_za_library.sql", "0035_charles_templates.sql", "0036_statement.sql"]);
});

test("the script never asks for a secret and never carries a real phone number", () => {
  const s = readFileSync(SETUP, "utf8");
  assert.doesNotMatch(s, /sk-or-v1-[A-Za-z0-9]|EAA[A-Za-z0-9]{20,}|service_role_key\s*=\s*['"]?[A-Za-z0-9]/i);
  // Synthetic numbers only (BEHAVIOR-MATRIX): nothing shaped like a real South African mobile outside the test prefix.
  const numbers = s.match(/\b27[0-9]{9}\b/g) ?? [];
  assert.deepEqual(numbers.filter((n) => !n.startsWith("2780993")), [], "a real-looking phone number is in the setup script");
});
