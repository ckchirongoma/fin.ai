// Charles — one script for a fresh Supabase project.
//
// Concatenates every migration in db/ in the order HANDOFF-DEPLOY.md gives,
// with a banner per file, into db/CHARLES-SETUP.sql: the one thing the founder
// pastes into Supabase → SQL Editor and runs. Each file is already safe to run
// twice, so the whole script is too. Regenerate whenever a migration changes:
//
//   npm run setup-sql        (node scripts/build-setup-sql.mjs > db/CHARLES-SETUP.sql)
//
// docs/SUPABASE-SETUP.md carries the paste-and-check instructions and the
// success criteria.

