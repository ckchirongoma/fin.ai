const banner = (name) => `\n\n-- ============================================================================\n-- ${name}\n-- ============================================================================\n\n`;

/** The whole script as a string. `today` is the date on the header line. */
export function build(today = new Date().toISOString().slice(0, 10)) {
  let out = `-- Charles — the whole database, in one script.
-- Generated by scripts/build-setup-sql.mjs on ${today} from the files in db/, in order.
-- Paste into Supabase → SQL Editor → New query → Run. Safe to run more than once.
-- Before running: Database → Extensions → enable "vector" (pgvector). Everything else is here.
-- Afterwards: run the checks in docs/SUPABASE-SETUP.md.
`;
  for (const f of ORDER) out += banner(f) + readFileSync(new URL(`../db/${f}`, import.meta.url), "utf8");
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.stdout.write(build());
